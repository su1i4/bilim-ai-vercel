type Topic = "rotation" | "multiply" | "ai" | "general";

const has = (s: string, ...w: string[]) => w.some((x) => s.includes(x));
function topicOf(about: string): Topic {
  const a = about.toLowerCase();
  if (has(a, "поворач", "столбец (", "вектор i", "растяг", "отраж", "бурат")) return "rotation";
  if (has(a, "строка на столбец", "строку на столбец", "правило")) return "multiply";
  if (has(a, "нейросет", "миллиард", "нейросеть")) return "ai";
  return "general";
}

