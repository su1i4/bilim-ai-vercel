export function levelReply(level: "simple" | "strict", about: string): AiReply {
  const topic = topicOf(about);
  return {
    text: (level === "simple" ? "🐣 Проще: " : "🎓 Строже: ") + TEXT[topic][level],
    widget: topic === "rotation" && level === "simple" ? { type: "matrix", matrix: [0, -1, 1, 0], caption: "две стрелки" } : undefined,
    suggestions: ["Как умножать матрицы?", "Готов к практике"],
  };
}
