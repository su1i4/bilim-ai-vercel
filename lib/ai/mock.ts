const has = (s: string, ...w: string[]) => w.some((x) => s.includes(x));

const HOOKS: Record<string, string> = {
  games: "В играх каждый поворот персонажа и камеры — это умножение на матрицу. Когда ты крутишь камеру в 3D-игре, видеокарта умножает матрицы миллионы раз в секунду.",
  photo: "Каждое фото — это матрица чисел-пикселей. Фильтры в Instagram и TikTok — это операции с матрицами.",
  football: "Честные рейтинги команд и прогнозы матчей считают через системы уравнений — то есть через матрицы (метод Массея).",
  money: "Экономисты через матрицы считают, сколько должна произвести каждая отрасль (модель Леонтьева), а банки — риски портфеля.",
};

function detectInterest(m: string): string | null {
  if (has(m, "игр", "game", "оюн")) return "games";
  if (has(m, "фото", "видео", "сүрөт", "insta")) return "photo";
  if (has(m, "футбол", "спорт")) return "football";
  if (has(m, "деньг", "финанс", "бизнес", "эконом", "акча")) return "money";
  return null;
}

